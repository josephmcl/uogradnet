#!/bin/sh
# Install the current checkout onto this server. Run via `sudo make deploy`
# (the Makefile builds the chatlog bot first). Idempotent: run it after every change.
set -eu

[ "$(id -u)" -eq 0 ] || { echo "run with sudo" >&2; exit 1; }
SRC=$(cd "$(dirname "$0")/.." && pwd)
SECRETS=/etc/uogradnet/secrets.env
UHOME=/home/unrealircd
[ -f "$SECRETS" ] || { echo "missing $SECRETS (see etc/secrets.env.example)" >&2; exit 1; }
cd "$SRC"
render() { sh deploy/render "$1" "$SECRETS"; }
say() { printf '==> %s\n' "$*"; }

say "UnrealIRCd config"
render unrealircd/unrealircd.conf.in > /tmp/unrealircd.conf.$$
install -o unrealircd -g unrealircd -m 600 /tmp/unrealircd.conf.$$ "$UHOME/unrealircd/conf/unrealircd.conf"
install -o unrealircd -g unrealircd -m 644 unrealircd/ircd.motd "$UHOME/unrealircd/conf/ircd.motd"
rm -f /tmp/unrealircd.conf.$$
sh deploy/renew-certs.sh --install-only
if ! out=$(runuser -u unrealircd -- "$UHOME/unrealircd/unrealircd" configtest 2>&1); then
	printf '%s\n' "$out" >&2
	exit 1
fi

say "Atheme config, allowmail module, email"
install -d -o irc -g irc /var/lib/atheme /var/log/atheme
install -d -m 755 /etc/atheme
render atheme/atheme.conf.in > /tmp/atheme.conf.$$
install -o root -g irc -m 640 /tmp/atheme.conf.$$ /etc/atheme/atheme.conf
rm -f /tmp/atheme.conf.$$
if ! cmp -s atheme/allowmail.c /usr/local/src/atheme/modules/nickserv/allowmail.c; then
	sh deploy/atheme-build.sh module
fi
install -m 644 atheme/email/register atheme/email/setemail /opt/atheme/email/
render msmtp/msmtprc.in > /tmp/msmtprc.$$
install -o root -g irc -m 640 /tmp/msmtprc.$$ /etc/msmtprc
rm -f /tmp/msmtprc.$$

say "chatlog bot"
install -m 755 chatlog/chatlog /usr/local/bin/chatlog
(cd /tmp && PGOPTIONS='-c client_min_messages=warning' runuser -u chatlog -- psql -q -d chatlog -v ON_ERROR_STOP=1) < chatlog/schema.sql
channels=$(awk -F'\t' 'NR > 1 && $2 == "yes" { printf "%s%s", sep, $1; sep = "," }' channels.tsv)
password=$(awk -F= '$1 == "CHATLOG_PASSWORD" { print substr($0, index($0, "=") + 1) }' "$SECRETS")
# the bot registers with the network's own address (uoregon.edu-only rule; an admin FVERIFYs it)
email=$(awk -F= '$1 == "MAIL_FROM" { print substr($0, index($0, "=") + 1) }' "$SECRETS")
umask 077
cat > /etc/uogradnet/chatlog.env <<EOF
# generated by deploy/deploy.sh from channels.tsv and secrets.env - do not edit
IRC_HOST=127.0.0.1
IRC_PORT=6667
IRC_NICK=chatlog
IRC_PASSWORD=$password
IRC_CHANNELS=$channels
ALLOW_INVITES=0
IRC_REGISTER_EMAIL=$email
DATABASE_URL=dbname=chatlog
EOF
umask 022
chown chatlog:chatlog /etc/uogradnet/chatlog.env

say "web"
install -m 644 lighttpd/lighttpd.conf /etc/lighttpd/lighttpd.conf
lighttpd -tt -f /etc/lighttpd/lighttpd.conf
install -d /srv/uogradnet/www/site
find /srv/uogradnet/www/site -mindepth 1 -delete
cp -r www/. /srv/uogradnet/www/site/
install -m 644 kiwi/config.json /srv/uogradnet/www/chat/static/config.json

say "systemd"
for unit in systemd/*; do
	install -m 644 "$unit" /etc/systemd/system/
done
systemctl daemon-reload
systemctl enable --quiet unrealircd atheme chatlog lighttpd uogradnet-renew.timer uogradnet-backup.timer

say "(re)starting"
systemctl reload-or-restart unrealircd     # reload = rehash, keeps users connected
systemctl reload-or-restart atheme
systemctl restart chatlog
systemctl reload-or-restart lighttpd
systemctl start uogradnet-renew.timer uogradnet-backup.timer

say "deployed $(git -C "$SRC" rev-parse --short HEAD 2>/dev/null || echo 'working tree')"
